"""Generation of replies, and of the predictions of a model on a Spider split."""

from pathlib import Path
from typing import TypedDict

from tqdm import tqdm
from transformers import PreTrainedModel, PreTrainedTokenizerBase

from text2sql.config import ModelConfig
from text2sql.prompt import Message, build_prompt
from text2sql.spider.predictions import Prediction, append_prediction, load_predictions
from text2sql.spider.samples import Sample


def _generate_batch(
    model: PreTrainedModel,
    tokenizer: PreTrainedTokenizerBase,
    conversations: list[list[Message]],
    config: ModelConfig,
) -> list[str]:
    """Generates the assistant replies to several conversations at once.

    Args:
        model (PreTrainedModel): Model from `load_model`.
        tokenizer (PreTrainedTokenizerBase): Tokenizer from `load_model`.
        conversations (list[list[Message]]): Conversations to reply to.
        config (ModelConfig): Config from `load_model_config`.

    Returns:
        list[str]: Replies, in the order of the conversations.
    """
    prompts = [
        tokenizer.apply_chat_template(messages, tokenize=False, add_generation_prompt=True)
        for messages in conversations
    ]
    tokenizer.padding_side = config["tokenizer"]["padding_side"]
    inputs = tokenizer(prompts, add_special_tokens=False, padding=True, return_tensors="pt").to(
        model.device
    )
    output = model.generate(**inputs, **config["generation"])
    return list(
        tokenizer.batch_decode(output[:, inputs["input_ids"].shape[1] :], skip_special_tokens=True)
    )


class PredictionCounts(TypedDict):
    """Counts of a generation run."""

    questions: int  # questions in the split
    generated: int  # predictions generated by this run
    already_done: int  # predictions that were already in the file


def generate_predictions(
    model: PreTrainedModel,
    tokenizer: PreTrainedTokenizerBase,
    samples: list[Sample],
    predictions_path: Path,
    batch_size: int,
    config: ModelConfig,
) -> PredictionCounts:
    """Generates a prediction for every question and appends it to a file.

    Args:
        model (PreTrainedModel): Model from `load_model`.
        tokenizer (PreTrainedTokenizerBase): Tokenizer from `load_model`.
        samples (list[Sample]): Questions to answer.
        predictions_path (Path): Predictions file.
        batch_size (int): Questions generated at once.
        config (ModelConfig): Config from `load_model_config`.

    Returns:
        PredictionCounts: Questions, predictions generated and predictions already in the file.
    """
    predictions_path.parent.mkdir(exist_ok=True)
    done = (
        {p["id"] for p in load_predictions(predictions_path)}
        if predictions_path.exists()
        else set()
    )
    prompts = [(i, build_prompt(sample)) for i, sample in enumerate(samples) if i not in done]
    # Shortest prompt first, so that a batch holds prompts of similar length and needs little padding
    todo = sorted(prompts, key=lambda item: sum(len(message["content"]) for message in item[1]))

    with (
        predictions_path.open("a") as file,
        tqdm(total=len(samples), initial=len(done)) as progress,
    ):
        for start in range(0, len(todo), batch_size):
            batch = todo[start : start + batch_size]
            replies = _generate_batch(model, tokenizer, [prompt for _, prompt in batch], config)
            for (i, _), predicted in zip(batch, replies):
                append_prediction(
                    file, Prediction(id=i, db_id=samples[i]["db_id"], predicted=predicted)
                )
            file.flush()
            progress.update(len(batch))
    return PredictionCounts(questions=len(samples), generated=len(todo), already_done=len(done))
